#!/usr/bin/env python3
"""Generate a reflective index of the crate: a module map and the public API
surface, read straight from `src/`.

Run `python3 tools/reflect.py` to (re)write `docs/reflection.md`, or
`python3 tools/reflect.py --check` to verify it is current (used in CI).

Standard library only.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = ROOT / "docs" / "reflection.md"

ITEM = re.compile(
    r"^\s*pub(?:\((?:crate|super|self)\))?\s+"
    r"(fn|struct|enum|trait|const|static|type|mod|union)\s+([A-Za-z_][A-Za-z0-9_]*)"
)
IMPL = re.compile(r"^\s*impl(?:<[^>]*>)?\s+(?:[A-Za-z0-9_:<>, ]+?\s+for\s+)?([A-Za-z_][A-Za-z0-9_]*)")
PUB_FN = re.compile(r"^\s*pub\s+(?:const\s+)?fn\s+([A-Za-z_][A-Za-z0-9_]*)")


def purpose(text: str) -> str:
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("//!"):
            return s[3:].strip()
        if s and not s.startswith("//"):
            break
    return ""


def public_items(text: str) -> list[tuple[str, str]]:
    """(kind, name) pairs for the crate's exported (`pub`) surface."""
    items: list[tuple[str, str]] = []
    impl_target: str | None = None
    depth = 0
    for raw in text.splitlines():
        line = raw.split("//", 1)[0]
        m = IMPL.match(line)
        if m and impl_target is None:
            impl_target = m.group(1)
            depth = 0
        if impl_target is not None:
            depth += line.count("{") - line.count("}")
            mf = PUB_FN.match(line)
            if mf:
                items.append(("fn", f"{impl_target}::{mf.group(1)}"))
            if depth <= 0 and "{" in text:
                # left the impl block
                if line.count("}") and depth <= 0:
                    impl_target = None
            continue
        mi = re.match(r"^\s*pub\s+(fn|struct|enum|trait|const|static|type|union)\s+([A-Za-z_][A-Za-z0-9_]*)", line)
        if mi:
            items.append((mi.group(1), mi.group(2)))
    return items


def render() -> str:
    files = sorted(p for p in SRC.rglob("*.rs"))
    lines: list[str] = []
    lines.append("# Crate reflection")
    lines.append("")
    lines.append(
        "Generated by `tools/reflect.py` from `src/`. Do not edit by hand: run "
        "`python3 tools/reflect.py` to regenerate, or `--check` to verify."
    )
    lines.append("")
    lines.append("## Modules")
    lines.append("")
    lines.append("| File | Purpose | sha256 |")
    lines.append("| --- | --- | --- |")
    api: list[tuple[str, str, str]] = []
    for path in files:
        text = path.read_text()
        rel = path.relative_to(ROOT).as_posix()
        digest = hashlib.sha256(text.encode()).hexdigest()[:12]
        lines.append(f"| `{rel}` | {purpose(text) or '—'} | `{digest}` |")
        for kind, name in public_items(text):
            api.append((name, kind, rel))
    lines.append("")
    lines.append("## Public API")
    lines.append("")
    if api:
        for name, kind, rel in sorted(api):
            lines.append(f"- `{name}` ({kind}) — `{rel}`")
    else:
        lines.append("_None yet._")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    content = render()
    check = "--check" in sys.argv[1:]
    if check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != content:
            print("docs/reflection.md is out of date; run: python3 tools/reflect.py", file=sys.stderr)
            return 1
        print("docs/reflection.md is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content)
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
